/**
 * Helper to construct a fresh WorkflowInstance from a template
 */
export function createInstanceFromTemplate(
  template: WorkflowTemplate,
  overrideVariables?: Record<string, any>,
  triggeredBy: { type: any; actor: string } = { type: 'DEMO_SIMULATOR', actor: 'Executive Presenter' }
): WorkflowInstance {
  const instanceId = `INST-${template.id.split('-')[1] || 'EXEC'}-${Date.now().toString().slice(-5)}`;
  const variables = {
    ...template.defaultVariables,
    ...(overrideVariables || {}),
  };

  // Interpolate initial variables into node payload templates
  const initialNodes = template.nodes.map((node) => ({
    ...node,
    status: 'PENDING' as const,
  }));

  const initialEdges = template.edges.map((edge) => ({
    ...edge,
    status: 'INACTIVE' as const,
  }));

  return {
    id: instanceId,
    workflowTemplateId: template.id,
    title: template.title,
    description: template.description,
    status: 'READY',
    createdAt: new Date().toISOString(),
    triggeredBy,
    context: {
      initialRequest: template.description,
      variables,
      stepOutputs: {},
    },
    nodes: initialNodes,
    edges: initialEdges,
    executionSpeedMs: 1000,
    logs: [],
    auditTrail: [
      {
        id: `AUD-${Date.now()}-${++auditIdCounter}`,
        timestamp: new Date().toISOString(),
        workflowId: instanceId,
        actorType: 'SYSTEM_CORE',
        actorName: 'Workflow Orchestration Engine',
        actionType: 'WORKFLOW_INITIALIZED',
        summary: `Initialized workflow instance for template [${template.title}]`,
        details: {},
        sha256Hash: `sha256_${Date.now().toString(16).padStart(16, '0')}_${auditIdCounter}`,
      },
    ],
  };
}

